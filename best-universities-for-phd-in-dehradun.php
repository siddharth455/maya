                            <h2 id="overview">1. Overview of PhD Programs in India</h2>
                            <p>A Doctor of Philosophy (PhD) is the highest academic degree awarded to scholars who contribute original, independent, and impactful research to their discipline. The degree signifies expertise, analytical depth, and the ability to advance knowledge beyond existing boundaries. Upon completion, candidates earn the academic title Doctor (Dr.).</p>
                            <p>In India, PhD programs are regulated by UGC PhD Regulations, ensuring quality, transparency, and research integrity across universities.</p>

                            <h4 class="font-weight-bold mt-4">Structure of a PhD Program in India</h4>
                            <p>Most PhD programs follow a structured academic pathway:</p>
                            <ul>
                                <li><strong>Coursework Phase:</strong> Research methodology and subject-specific courses.</li>
                                <li><strong>Comprehensive Evaluation:</strong> Written exams and/or synopsis presentations.</li>
                                <li><strong>Research Phase:</strong> Original research under a recognized supervisor.</li>
                                <li><strong>Thesis Submission & Viva Voce:</strong> Final evaluation by expert internal and external panels.</li>
                            </ul>

                            <h4 class="font-weight-bold mt-4">Popular PhD Disciplines in India</h4>
                            <ul>
                                <li>Sciences (Physics, Chemistry, Biology, Environmental Science)</li>
                                <li>Engineering & Technology</li>
                                <li>Management & Business Studies</li>
                                <li>Humanities & Social Sciences</li>
                                <li>Law & Public Policy</li>
                                <li>Medical & Allied Health Sciences</li>
                            </ul>

