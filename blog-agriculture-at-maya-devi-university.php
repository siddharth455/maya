                            <h3>Agriculture at Maya Devi University</h3>

<h2>About</h2>
<p>The School of Agriculture and Technology, Maya Devi University, Selaqui, Dehradun is a dynamic academic and research institution committed to advancing sustainable agricultural practices, technological innovation and rural development. The department of Agriculture was established in 2013 and school of Agriculture &amp; Technology in 2024. The school addresses the evolving challenges in food production, environmental sustainability and technological advancement and plays a vital role in training the next generation of professionals in agriculture and allied sciences. Rooted in a tradition of excellence and practical learning, the school offers programs that integrate modern scientific knowledge with hands-on experience in areas such as plant breeding, crop and soil science, horticultural sciences, agricultural engineering, food technology, microbiology, biochemistry, plant biotechnology and environmental management. The curriculum is designed to meet the needs of a rapidly changing agricultural landscape and to equip students with the skills to drive innovation and impact.</p>
<p>Our key focus areas are: Sustainable crop production, Soil health and fertility management, Climate-resilient agriculture, Farm machinery and automation, Water resource management, post-harvest handling and storage technologies, Waste-to-bioenergy conversion through microbial processes, Genetic improvement of crops, Genetic engineering of microbes for enhanced agricultural applications, Molecular biology and biotechnology applications, Bioinformatics and emerging technologies, Sustainable land use and conservation, Agroforestry and biodiversity, Climate-smart agriculture practices, Precision agriculture and data-driven farming, Farmer education and outreach programs, Community-based innovation and rural empowerment.</p>

