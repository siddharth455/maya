(function () {
  /* --- Floating Particles --- */
  var container = document.getElementById('emvParticles');
  if (container) {
    for (var i = 0; i < 22; i++) {
      var p = document.createElement('span');
      p.className = 'emv-particle';
      var size = Math.random() * 5 + 2;
      p.style.cssText = [
        'width:' + size + 'px',
        'height:' + size + 'px',
        'left:' + (Math.random() * 100) + '%',
        'top:' + (Math.random() * 100) + '%',
        'animation-duration:' + (Math.random() * 6 + 4) + 's',
        'animation-delay:' + (Math.random() * 5) + 's',
        'opacity:' + (Math.random() * 0.5 + 0.2)
      ].join(';');
      container.appendChild(p);
    }
  }
 
  /* --- Scroll Reveal --- */
  var reveals = document.querySelectorAll('[data-emv-reveal], .emv-features-grid');
  if (!reveals.length) return;
 
  var io = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        var el = entry.target;
        var delay = parseInt(el.getAttribute('data-emv-delay') || '0', 10);
        setTimeout(function () { el.classList.add('emv-visible'); }, delay);
        io.unobserve(el);
      }
    });
  }, { threshold: 0.15 });
 
  reveals.forEach(function (el) { io.observe(el); });
})();
</script>
