                            <h2 id="what-is-civil">2. What is Civil Engineering?</h2>
                            <p>Civil engineering focuses on the planning, design, construction, operation, and maintenance of infrastructure such as:</p>
                            <ul>
                                <li>Roads and highways</li>
                                <li>Bridges and tunnels</li>
                                <li>Airports and seaports</li>
                                <li>Residential and commercial buildings</li>
                                <li>Water supply and sanitation systems</li>
                                <li>Railways and metro networks</li>
                            </ul>
                            <p>It also ensures structural safety, sustainability, and environmental compliance across all projects.</p>

