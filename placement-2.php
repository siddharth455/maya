<script>
document.addEventListener('DOMContentLoaded', function () {
  /* =========================================
     1. CONTINUOUS MARQUEE SLIDER
  ========================================= */
  new Swiper('.placement-partners', {
    loop: true,
    slidesPerView: 'auto',
    spaceBetween: 24,
    speed: 4000,
    autoplay: {
      delay: 0,
      disableOnInteraction: false
    },
    allowTouchMove: false
  });

  /* =========================================
     2. IMAGE CROSSFADE SLIDER
  ========================================= */
  let slides = document.querySelectorAll(".pl-slide");
  let slideIndex = 0;
  if(slides.length > 0) {
    setInterval(() => {
      slides[slideIndex].classList.remove("active");
      slideIndex = (slideIndex + 1) % slides.length;
      slides[slideIndex].classList.add("active");
    }, 4000);
  }

  /* =========================================
     3. NUMBER COUNTER ANIMATION
  ========================================= */
  const counters = document.querySelectorAll('.fc-num');
  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = parseFloat(el.getAttribute('data-target') || '0');
        const decimals = parseInt(el.getAttribute('data-decimals') || '0', 10);
        const duration = 2000;
        const start = performance.now();

        function step(now) {
          const progress = Math.min((now - start) / duration, 1);
          const ease = progress === 1 ? 1 : 1 - Math.pow(2, -10 * progress);
          const current = ease * target;
          
          el.textContent = decimals > 0 ? current.toFixed(decimals) : Math.floor(current);
          
          if (progress < 1) {
            requestAnimationFrame(step);
          }
        }
        requestAnimationFrame(step);
        obs.unobserve(el);
      }
    });
  }, { threshold: 0.5 });

  counters.forEach(c => observer.observe(c));
});
</script>